func bannedAt(t *testing.T, path, src string) []string {
	t.Helper()
	groups, err := bannedComments(path, []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	var at []string
	for _, g := range groups {
		at = append(at, fmt.Sprintf("%d+%d", g.line, g.lines))
	}
	return at
}

func TestBannedCommentsKeepOnlyGodocAndDirectives(t *testing.T) {
	src := `// Package p is documented.
package p

//go:generate echo kept

// Exported is shown by godoc.
func Exported() {
	// banned: inside a body
	_ = 1 // banned: trailing
}

// unexported is not shown by godoc.
func unexported() {}

// T is exported.
type T struct {
	// Field is exported.
	Field int
	Line  int // Line is exported too.
	// hidden is not.
	hidden int
	nested struct {
		// Deep is hidden under an unexported field.
		Deep int
	}
	Nested struct {
		// Shown is exported under an exported field.
		Shown int
	}
}

// Method is exported, on an exported type.
func (T) Method() {}

type u struct {
	// Field of an unexported type is not shown.
	Field int
}

// Method on an unexported type is not shown.
func (u) Method() {}

// Group declares one exported name.
var (
	// A is exported.
	A = 1
	b = 2 // banned: unexported value
)

/* banned
   block of
   three lines */

// I is exported.
type I interface {
	// Do is exported.
	Do()
	// do is not.
	do()
}

// E embeds.
type E struct {
	// T is embedded and exported.
	T
	// u is embedded and unexported.
	u
}

// Ptr is exported, on a pointer receiver.
func (*T) Ptr() {}

// G is generic.
type G[K any] struct{}

// Get is exported, on a generic receiver.
func (G[K]) Get() {}
`
	got := bannedAt(t, "p.go", src)
	want := []string{"8+1", "9+1", "12+1", "20+1", "23+1", "36+1", "40+1", "47+1", "50+3", "58+1", "66+1"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("banned at %v, want %v", got, want)
	}
}

func TestBannedCommentsBanEveryDocInTestFiles(t *testing.T) {
	src := `//go:build linux

// Package p is documented.
package p

// TestX is exported, but test files have no godoc.
func TestX() {}
`
	got := bannedAt(t, "p_test.go", src)
	want := []string{"3+1", "6+1"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("banned at %v, want %v", got, want)
	}
}

func TestBannedCommentsKeepGeneratedHeader(t *testing.T) {
	src := "// Code generated by stringer; DO NOT EDIT.\n\npackage p\n\nvar x = 1 // banned\n"
	got := bannedAt(t, "p.go", src)
	want := []string{"5+1"}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("banned at %v, want %v", got, want)
	}
}

func TestCompareFailsOnEveryChange(t *testing.T) {
	counts := map[string]int{"grew.go": 3, "same.go": 2, "shrank.go": 1, "new.go": 1}
	base := map[string]int{"grew.go": 2, "same.go": 2, "shrank.go": 4, "gone.go": 5}
	var files []string
	for _, p := range compare(counts, base) {
		files = append(files, strings.SplitN(p, ":", 2)[0])
	}
	want := []string{"gone.go", "grew.go", "new.go", "shrank.go"}
	if !reflect.DeepEqual(files, want) {
		t.Errorf("compare flagged %v, want %v", files, want)
	}
}

func TestRunRatchetsAgainstTheBaseline(t *testing.T) {
	root := t.TempDir()
	write := func(rel, text string) {
		t.Helper()
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module m\n")
	write("a/a.go", "package a\n\nvar x = 1 // banned\n")
	write("a/testdata/t.go", "package t\n\n// skipped\n")
	write(".hidden/h.go", "package h\n\n// skipped\n")
	write("vendor/v/v.go", "package v\n\n// skipped\n")
	write("tools/go.mod", "module tools\n")
	write("tools/t.go", "package t\n\n// skipped: nested module\n")
	baseline := filepath.Join(root, "baseline.txt")

	if err := run(root, baseline, true); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(baseline)
	wantBaseline := "# Banned comment lines allowed per file; only ever lower these.\n# Regenerate with: just comment-baseline\n1 a/a.go\n"
	if string(data) != wantBaseline {
		t.Fatalf("baseline:\n%s", data)
	}
	if err := run(root, baseline, false); err != nil {
		t.Errorf("unchanged tree: %v", err)
	}
	write("a/a.go", "package a\n\n// new\nvar x = 1 // banned\n")
	if err := run(root, baseline, false); err == nil || !strings.Contains(err.Error(), "delete the new comments") {
		t.Errorf("grown file: err = %v", err)
	}
	write("a/a.go", "package a\n\nvar x = 1\n")
	if err := run(root, baseline, false); err == nil || !strings.Contains(err.Error(), "lock in the drop") {
		t.Errorf("shrunk file: err = %v", err)
	}
}

func TestReadBaselineRejectsMalformedLines(t *testing.T) {
	p := filepath.Join(t.TempDir(), "baseline.txt")
	if err := os.WriteFile(p, []byte("# header\n\nthree a.go\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := readBaseline(p); err == nil || !strings.Contains(err.Error(), ":3:") {
		t.Errorf("err = %v, want a line-3 error", err)
	}
}

